const assert=require('node:assert/strict');
const fs=require('node:fs');
const p=require('node:path').join(__dirname,'../desktop/tasks-core.js');
assert.ok(fs.existsSync(p),'Debe existir núcleo de tareas');
const core=require(p);
assert.deepEqual(core.fromNote('Comprar papel;\nLlamar proveedor').map(t=>t.action),['Comprar papel','Llamar proveedor']);
assert.equal(core.fromNote('comprar papel; comprar   papel').length,1);
assert.equal(core.fromNote(' ; \n').length,0);
assert.throws(()=>core.fromNote('x'.repeat(10001)),/10000/);
assert.throws(()=>core.fromNote(null),/texto/);
const tasks=core.fromNote('Ana: revisar mañana');
assert.equal(tasks[0].responsible,''); assert.equal(tasks[0].deadline,'');
assert.equal(tasks[0].done,false);
assert.ok(core.toMarkdown(tasks).includes('- [ ] Ana: revisar mañana'));
tasks[0].done=true;tasks[0].responsible='Ana';
assert.ok(core.toMarkdown(tasks).includes('- [x]'));
assert.ok(core.toMarkdown(tasks).includes('Responsable: Ana'));
assert.equal(core.toMarkdown([{action:'<script>x</script>\n# Otro',done:false,responsible:'',deadline:''}]).includes('<script>'),false);
assert.equal(JSON.parse(core.toJSON(tasks)).tasks[0].done,true);
assert.equal(core.toJSON(tasks).includes('secret'),false);
console.log('Tasks core: 13 assertions PASS');
